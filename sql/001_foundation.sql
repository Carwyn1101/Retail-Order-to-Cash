\set ON_ERROR_STOP on
-- M1-T01 v1.1: source/evaluation storage only; no ingestion or business calculations.
BEGIN;
SET LOCAL TIME ZONE 'UTC';

CREATE SCHEMA IF NOT EXISTS bronze;
CREATE SCHEMA IF NOT EXISTS core;

CREATE TABLE IF NOT EXISTS bronze.input_batches (
    batch_id TEXT PRIMARY KEY,
    source_name TEXT NOT NULL,
    batch_sequence BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL UNIQUE,
    content_digest TEXT NOT NULL,
    input_reference TEXT NOT NULL,
    row_count BIGINT NOT NULL CHECK (row_count >= 0),
    status TEXT NOT NULL DEFAULT 'REGISTERED'
        CHECK (status IN ('REGISTERED', 'COMMITTED', 'FAILED')),
    scope_complete BOOLEAN NOT NULL DEFAULT FALSE,
    registered_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    committed_at TIMESTAMPTZ,
    CHECK ((status = 'COMMITTED') = (committed_at IS NOT NULL))
);

-- Raw business fields intentionally permit NULL, unknown statuses, invalid currencies,
-- conflicting versions and orphan IDs. raw_payload is the complete original record as
-- TEXT, not JSONB: even malformed JSON and textual monetary/time representations survive.
-- Parsing failures leave normalized fields NULL; never cast/round raw money on write.
CREATE TABLE IF NOT EXISTS bronze.orders_source (
    row_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    batch_id TEXT NOT NULL REFERENCES bronze.input_batches (batch_id),
    source_row_number BIGINT NOT NULL CHECK (source_row_number > 0),
    source_record_id TEXT,
    order_id TEXT,
    source_version TEXT,
    event_at TIMESTAMPTZ,
    source_updated_at TIMESTAMPTZ,
    order_status TEXT,
    amount_raw TEXT,
    amount_cents BIGINT,
    currency TEXT,
    payment_due_at TIMESTAMPTZ,
    raw_payload TEXT NOT NULL,
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (batch_id, source_row_number)
);

CREATE TABLE IF NOT EXISTS bronze.payments_source (
    row_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    batch_id TEXT NOT NULL REFERENCES bronze.input_batches (batch_id),
    source_row_number BIGINT NOT NULL CHECK (source_row_number > 0),
    source_record_id TEXT,
    payment_id TEXT,
    order_id TEXT,
    external_charge_ref TEXT,
    source_version TEXT,
    event_at TIMESTAMPTZ,
    source_updated_at TIMESTAMPTZ,
    financial_effective_at TIMESTAMPTZ,
    payment_status TEXT,
    amount_raw TEXT,
    amount_cents BIGINT,
    currency TEXT,
    raw_payload TEXT NOT NULL,
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (batch_id, source_row_number)
);

CREATE TABLE IF NOT EXISTS bronze.refunds_source (
    row_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    batch_id TEXT NOT NULL REFERENCES bronze.input_batches (batch_id),
    source_row_number BIGINT NOT NULL CHECK (source_row_number > 0),
    source_record_id TEXT,
    refund_id TEXT,
    order_id TEXT,
    payment_id TEXT,
    source_version TEXT,
    event_at TIMESTAMPTZ,
    source_updated_at TIMESTAMPTZ,
    financial_effective_at TIMESTAMPTZ,
    refund_status TEXT,
    amount_raw TEXT,
    amount_cents BIGINT,
    currency TEXT,
    raw_payload TEXT NOT NULL,
    ingested_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (batch_id, source_row_number)
);

CREATE TABLE IF NOT EXISTS core.evaluation_runs (
    run_id TEXT PRIMARY KEY,
    evaluation_key TEXT NOT NULL,
    snapshot_cutoff BIGINT NOT NULL,
    evaluation_as_of TIMESTAMPTZ NOT NULL,
    rules_version TEXT NOT NULL,
    status TEXT NOT NULL,
    started_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    finished_at TIMESTAMPTZ,
    error_details TEXT
);

CREATE TABLE IF NOT EXISTS core.reconciliation_results (
    evaluation_key TEXT NOT NULL,
    order_id TEXT NOT NULL,
    expected_cents BIGINT,
    payments_cents BIGINT,
    refunds_cents BIGINT,
    net_cents BIGINT,
    overall_status TEXT NOT NULL CHECK (overall_status IN (
        'MATCHED', 'PENDING', 'EXCEPTION', 'UNDETERMINED', 'NOT_APPLICABLE'
    )),
    PRIMARY KEY (evaluation_key, order_id)
);

CREATE TABLE IF NOT EXISTS core.reconciliation_findings (
    evaluation_key TEXT NOT NULL,
    order_id TEXT NOT NULL,
    reason_code TEXT NOT NULL CHECK (reason_code IN (
        'MISSING_PAYMENT', 'DUPLICATE_PAYMENT', 'AMOUNT_MISMATCH', 'REFUND_MISMATCH'
    )),
    evidence_refs JSONB NOT NULL,
    details JSONB NOT NULL,
    PRIMARY KEY (evaluation_key, order_id, reason_code),
    FOREIGN KEY (evaluation_key, order_id)
        REFERENCES core.reconciliation_results (evaluation_key, order_id)
);

CREATE TABLE IF NOT EXISTS core.dq_findings (
    evaluation_key TEXT NOT NULL,
    finding_key TEXT NOT NULL,
    source_name TEXT NOT NULL,
    source_row_id BIGINT,
    batch_id TEXT REFERENCES bronze.input_batches (batch_id),
    dq_code TEXT NOT NULL,
    details JSONB NOT NULL,
    PRIMARY KEY (evaluation_key, finding_key)
);

COMMENT ON TABLE bronze.input_batches IS
    'Future ingestion must enforce content identity, legal state transitions, source/batch '
    'consistency, row counts, scope readiness, deterministic replay and committed-batch '
    'immutability (including child rows). PK/UNIQUE constraints do not establish immutability. '
    'Sequence gaps are valid; a sequence number is not a business event timestamp.';
COMMENT ON TABLE core.evaluation_runs IS
    'run_id identifies an attempt; evaluation_key is shared by retries. Future evaluation '
    'writer must derive/validate keys and reject conflicting snapshot/as-of/rules reuse. '
    'This schema alone does not enforce that context invariant or atomic publication.';
COMMENT ON TABLE core.dq_findings IS
    'source_row_id is polymorphic across three raw tables and intentionally has no FK. '
    'Findings can exist without a valid order or a source-row assignment.';
COMMENT ON COLUMN bronze.orders_source.ingested_at IS
    'Technical ingestion time only; never determines business source-version precedence.';
COMMENT ON COLUMN bronze.payments_source.ingested_at IS
    'Technical ingestion time only; never determines business source-version precedence.';
COMMENT ON COLUMN bronze.refunds_source.ingested_at IS
    'Technical ingestion time only; never determines business source-version precedence.';

COMMIT;
